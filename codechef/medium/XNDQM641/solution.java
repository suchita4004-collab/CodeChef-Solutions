class Codechef {
    public static void main(String[] args) {
        int[] scores = {85, 90, 78, 92, 88}; // Declare and initialize array

        for (int i = 0; i < scores.length; i++) { // Loop through array elements
            System.out.println("Score " + (i + 1) + ": " + scores[i]);
        }
    }
}